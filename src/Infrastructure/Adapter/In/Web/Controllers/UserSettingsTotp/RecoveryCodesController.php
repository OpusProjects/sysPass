namespace SP\Infrastructure\Adapter\In\Web\Controllers\UserSettingsTotp;

use Exception;
use SP\Domain\Common\Attributes\Action;
use SP\Domain\Common\Dtos\ActionResponse;
use SP\Domain\Common\Enums\ResponseType;
use SP\Domain\Core\Events\Event;

use function SP\__u;
use function SP\processException;

/**
 * Replace the recovery codes, given a current code
 */
final class RecoveryCodesController extends UserSettingsTotpBase
{
    #[Action(ResponseType::JSON)]
    public function recoveryCodesAction(): ActionResponse
    {
        try {
            $this->requireCode();

            $codes = $this->userTotpService->generateRecoveryCodes($this->getUserId());

            $this->notify(__u('New recovery codes issued'));

            return ActionResponse::ok(__u('New recovery codes issued'), ['recoveryCodes' => $codes]);
        } catch (Exception $e) {
            processException($e);

            $this->eventDispatcher->notify(new Event('exception', $e));

            return ActionResponse::error($e->getMessage());
        }
    }
}
